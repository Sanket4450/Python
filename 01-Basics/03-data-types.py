# Data Types

a = 10

print(a) # prints the value of the variable a
print(type(a)) # prints the type of the variable a

b = 3.14

print(b) # prints the value of the variable b
print(type(b)) # prints the type of the variable b

c = 'Hello, World!'

print(c) # prints the value of the variable c
print(type(c)) # prints the type of the variable c

d = """This
is a multi-line
string."""

print(d) # prints the value of the variable d
print(type(d)) # prints the type of the variable d

print(len(d)) # prints the length of the variable d

print('multi' in d) # checks if 'multi' is in the variable d and prints the result

d = True

print(d) # prints the value of the variable d
print(type(d)) # prints the type of the variable d
