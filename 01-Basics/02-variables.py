a = 'Hello, World!' # assigns a string to a variable

print(a) # prints the value of the variable a

b = 5 # assigns an integer to a variable

print(b) # prints the value of the variable b

print(type(a)) # prints the type of the variable a
print(type(b)) # prints the type of the variable b

x, y, z = 10, 20, 30 # assigns values to multiple variables in a single line

print(x) # prints the value of the variable x
print(y) # prints the value of the variable y
print(z) # prints the value of the variable z

p = q = r = 'Python' # assigns single value to multiple variables in a single line

print(p) # prints the value of the variable p
print(q) # prints the value of the variable q
print(r) # prints the value of the variable r