a = int(2.3) # converts the float 2.3 to an integer and assigns it to variable a

print(a)  # prints the value of the variable a
print(type(a))  # prints the type of the variable a

b = float(5) # converts the integer 5 to a float and assigns it to variable b

print(b)  # prints the value of the variable b
print(type(b))  # prints the type of the variable b

c = complex(3) # converts the integer 3 to a complex number and assigns it to variable c

print(c)  # prints the value of the variable c
print(type(c))  # prints the type of the variable c

d = str(10) # converts the integer 10 to a string and assigns it to variable d

print(d)  # prints the value of the variable d
print(type(d))  # prints the type of the variable d

e = int("20") # converts the string "20" to an integer and assigns it to variable e

print(e)  # prints the value of the variable e
print(type(e))  # prints the type of the variable e

print(15 == str(15)) # prints False because 15 is an integer and str(15) is a string, so they are not equal

print(1 + True) # prints 2 because True is considered as 1 in arithmetic operations

print(4 - False) # prints 4 because False is considered as 0 in arithmetic operations

print(True - False) # prints 1 because True is considered as 1 and False is considered as 0 in arithmetic operations
