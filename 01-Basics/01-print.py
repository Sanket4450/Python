# Basic Hello World program in Python

print("Hello, World!") # works with double quotes

print('Hello, World!') # works with single quotes

print('Hello', end=' ') # prints without a newline
print('World!') # prints on the same line as the previous print statement

# Numbers

print(5) # prints an integer
print(3.14) # prints a float
print(2 + 3) # prints the result of an addition operation

print('The sum of 2 and 3 is:', 2 + 3) # prints a string and the result of an addition operation

